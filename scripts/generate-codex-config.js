#!/usr/bin/env node
/**
 * Generates ~/.codex/config.toml from noetix.config and ui.config.
 *
 * Run: node scripts/generate-codex-config.js
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parse } from 'smol-toml';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PROJECT_ROOT = path.resolve(__dirname, '..');

function loadToml(filename) {
  return parse(fs.readFileSync(path.join(PROJECT_ROOT, filename), 'utf-8'));
}

function expandHome(p) {
  if (typeof p === 'string' && p.startsWith('~/')) {
    return path.join(process.env.HOME || '/root', p.slice(2));
  }
  return p;
}

const noetix = loadToml('noetix.config');
const ui = loadToml('ui.config');

const model = noetix.codex?.model || 'gpt-5.3-codex';
const effort = noetix.codex?.reasoning_effort || 'xhigh';
const remoteBase = ui.backend?.url || 'http://10.0.0.50:8001';
const socksProxy = ui.backend?.socks_proxy || '';
const downloadsDir = expandHome(ui.playwright?.downloads_dir || '~/.cache/noetix-playwright');

const kbMcp = noetix.codex?.mcp_servers?.kb || {};
const contentMcp = noetix.codex?.mcp_servers?.content || {};
const playwrightMcp = noetix.codex?.mcp_servers?.playwright || {};

const kbServerPath = path.join(PROJECT_ROOT, 'ui', 'src', 'gateway', 'kb-mcp-server.js');
const contentServerPath = path.join(PROJECT_ROOT, 'ui', 'src', 'gateway', 'content-mcp-server.js');
const playwrightOutputDir = expandHome(playwrightMcp.output_dir || '~/.cache/noetix-playwright');
const cdpEndpoint = playwrightMcp.cdp_endpoint || 'http://localhost:9222';

const toml = `# Auto-generated by noetix/scripts/generate-codex-config.js
# Do not edit manually — re-run the script after changing noetix.config or ui.config.

model = "${model}"
model_reasoning_effort = "${effort}"

[mcp_servers.noetix-kb]
command = "node"
args = ["${kbServerPath}"]
startup_timeout_sec = ${kbMcp.startup_timeout_sec || 10.0}
tool_timeout_sec = ${kbMcp.tool_timeout_sec || 30.0}

[mcp_servers.noetix-kb.env]
REMOTE_BASE = "${remoteBase}"
SOCKS_PROXY = "${socksProxy}"

[mcp_servers.noetix-content]
command = "node"
args = ["${contentServerPath}"]
startup_timeout_sec = ${contentMcp.startup_timeout_sec || 10.0}
tool_timeout_sec = ${contentMcp.tool_timeout_sec || 600.0}

[mcp_servers.noetix-content.env]
REMOTE_BASE = "${remoteBase}"
DOWNLOADS_DIR = "${downloadsDir}"

[mcp_servers.noetix-playwright]
command = "${playwrightMcp.command || 'playwright-mcp'}"
args = ["--cdp-endpoint", "${cdpEndpoint}"]
startup_timeout_sec = ${playwrightMcp.startup_timeout_sec || 15.0}
tool_timeout_sec = ${playwrightMcp.tool_timeout_sec || 60.0}

[mcp_servers.noetix-playwright.env]
OUTPUT_DIR = "${playwrightOutputDir}"
`;

const codexDir = path.join(process.env.HOME || '/root', '.codex');
fs.mkdirSync(codexDir, { recursive: true });
const configPath = path.join(codexDir, 'config.toml');

// Back up existing config if present
if (fs.existsSync(configPath)) {
  const backup = configPath + '.bak';
  fs.copyFileSync(configPath, backup);
  console.log(`Backed up existing config to ${backup}`);
}

fs.writeFileSync(configPath, toml);
console.log(`Generated ${configPath}`);
console.log(`  model: ${model}`);
console.log(`  effort: ${effort}`);
console.log(`  backend: ${remoteBase}`);
console.log(`  MCP servers: noetix-kb, noetix-content, noetix-playwright`);
